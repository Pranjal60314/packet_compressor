import re


def parse_verilog_log(log_text):
    # Split log into lines
    lines = log_text.strip().splitlines()

    blocks = []
    current_inputs = []

    for line in lines:
        line = line.strip()

        # Match input buffer sample
        input_match = re.search(r"Input BUffer data:\s*([0-9a-fAxX]+)", line)
        if input_match:
            current_inputs.append(input_match.group(1))
            continue

        # Match Optimal K calculation line
        k_match = re.search(
            r"OPTIMAL K CALCULATED:\s*(\d+|x)\s*MINIMUM LENGTH:\s*([0-9a-fAxX]+)",
            line,
        )
        if k_match:
            k_val = k_match.group(1)
            min_len = k_match.group(2)

            # Store current block
            blocks.append({
                "inputs": list(current_inputs),
                "k": k_val,
                "min_length": min_len,
                "outputs": [],
            })
            current_inputs.clear()
            continue

        # Match output packed words
        out_match = re.search(
            r"PACKED OUT TARGET WORD:\s*([0-9a-fAxX]+)", line
        )
        if out_match:
            if blocks:
                blocks[-1]["outputs"].append(out_match.group(1))

    return blocks


def print_parsed_results(blocks):
    for i, block in enumerate(blocks, start=1):
        print(f"{'='*20} PACKET {i} {'='*20}")
        print(f"Optimal K : {block['k']}")
        print(f"Min Length: {block['min_length']}")
        print(f"Input Samples ({len(block['inputs'])}):")

        # Print inputs in 2 columns for neat readability
        for j in range(0, len(block["inputs"]), 2):
            pair = block["inputs"][j : j + 2]
            print("  " + "   ".join(f"[{idx+j+1:02d}] 0x{val}" for idx, val in enumerate(pair)))

        print(f"Output Words ({len(block['outputs'])}):")
        for idx, out_word in enumerate(block["outputs"], start=1):
            print(f"  Word {idx}: 0x{out_word}")
        print("\n")


